"""End-to-end check of the announcement against REAL captured bridge records.

The unit tests pin the rule; this replays records the bridge actually emitted and asks
what the UI would paint. Without it, a passing unit suite only proves the rule is
internally consistent -- not that real records satisfy its preconditions.

Reads the newest capture under temp/real-subagent-fold-e2e/.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(r"D:\git_repos\GenericAgent")
UI = REPO / "frontends" / "ink" / "ui"
CAPTURES = REPO / "temp" / "real-subagent-fold-e2e"


def newest_records() -> tuple[Path, dict]:
    captures = sorted(CAPTURES.glob("*/bridge-events.jsonl"), key=lambda p: p.stat().st_mtime)
    for path in reversed(captures):
        latest: dict[str, dict] = {}
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            if event.get("type") != "agent_snapshot":
                continue
            for record in event.get("snapshot", {}).get("records", []):
                latest[record.get("executionId")] = record
        if latest:
            return path, latest
    raise SystemExit("no captured agent_snapshot found")


DRIVER = r"""// Generated by replay_real_subagent_records.py -- reads records from argv and prints
// what the UI would announce for each. Written to a temp file because `tsx -e` cannot
// resolve a relative import.
import { agentNoticeFromRecord } from '../src/agentNotice.js'

const records = JSON.parse(process.argv[2] ?? '[]')
const out = records.map((r: Record<string, unknown>) => {
  const n = agentNoticeFromRecord(r as never)
  return n
    ? { name: n.name, ok: n.ok, word: n.word }
    : { name: r.executionId, ok: null, word: 'no-announcement' }
})
console.log(JSON.stringify(out))
"""


def main() -> int:
    path, records = newest_records()
    print(f"capture: {path.relative_to(REPO)}  ({len(records)} record(s))\n")

    for execution_id, record in records.items():
        print(f"  {execution_id}")
        for key in ("status", "sourceStatus", "turnStatus"):
            print(f"    {key:14} = {record.get(key)!r}")

    driver = UI / "scripts" / "_replay_driver.ts"
    driver.write_text(DRIVER, encoding="utf-8", newline="\n")
    try:
        proc = subprocess.run(
            ["npx", "tsx", str(driver), json.dumps(list(records.values()))],
            cwd=UI,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            shell=True,
        )
    finally:
        driver.unlink(missing_ok=True)

    if proc.returncode != 0:
        print("DRIVER FAILED\n" + (proc.stderr or "")[-2000:])
        return 1

    lines = [line for line in (proc.stdout or "").strip().splitlines() if line.strip()]
    if not lines:
        print("DRIVER PRODUCED NO OUTPUT\n" + (proc.stderr or "")[-2000:])
        return 1
    notices = json.loads(lines[-1])
    print("\nwhat the UI would announce:")
    failures = []
    for notice in notices:
        mark = "OK  " if notice["ok"] else "FAIL"
        print(f"  [{mark}] {notice['name']}: {notice['word']}")
        if not notice["ok"]:
            failures.append(notice)

    if failures:
        print(f"\n{len(failures)} of {len(notices)} finished child(ren) would be announced as failed")
        return 1
    print(f"\nall {len(notices)} child(ren) announced as completed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
